// Builds screen/app.js: the screen as ONE classic script, from the ES modules in src/screen and src/core.
//   node scripts/build-screen.mjs          writes screen/app.js
//   node scripts/build-screen.mjs --check  fails if screen/app.js is not what the sources give (a test runs this)
//
// Why (as in Clotheskin): the Kindroid frame also runs on phones and older Safari, and every screen file is uploaded
// one by one. One classic script means no module loading and one file. No dependency: the sources keep to a small,
// checked subset of module syntax (named imports and `export function|const`), and each module becomes a function in
// a tiny registry, so two modules can use the same names.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const ENTRY = 'src/screen/main.js';
const OUT = 'screen/app.js';
const posix = (/** @type {string} */ p) => p.split(sep).join('/');

const IMPORT = /^import\s*\{([^}]*)\}\s*from\s*'([^']+)';\s*$/;
const EXPORT = /^export\s+(?:async\s+)?(function|const|let|class)\s+([A-Za-z_$][\w$]*)/;

/** @param {string} file repo-relative */
function load(file) {
  const code = readFileSync(join(ROOT, file), 'utf8');
  /** @type {string[]} */ const deps = [];
  /** @type {string[]} */ const names = [];
  const lines = code.split('\n').map((line, i) => {
    const where = `${file}:${i + 1}`;
    if (/^\s*import\b/.test(line)) {
      const m = IMPORT.exec(line);
      if (!m) throw new Error(`${where}: only one-line named imports are supported`);
      if (/\bas\b/.test(m[1])) throw new Error(`${where}: "import { a as b }" is not supported`);
      if (m[1].includes('type ')) throw new Error(`${where}: type imports belong in JSDoc`);
      const dep = posix(relative(ROOT, join(ROOT, dirname(file), m[2])));
      deps.push(dep);
      return `const {${m[1]}} = req(${JSON.stringify(dep)});`;
    }
    if (/^\s*export\b/.test(line)) {
      const m = EXPORT.exec(line);
      if (!m) throw new Error(`${where}: only "export function|const|let|class name" is supported`);
      names.push(m[2]);
      return line.replace(/^export\s+/, '');
    }
    return line;
  });
  return { file, deps, body: lines.join('\n'), names };
}

export function build() {
  /** @type {Map<string, ReturnType<typeof load>>} */
  const mods = new Map();
  /** @param {string} f */
  const visit = (f) => {
    if (mods.has(f)) return;
    const m = load(f);
    mods.set(f, m);
    m.deps.forEach(visit);
  };
  visit(ENTRY);
  const parts = [...mods.values()].sort((a, b) => a.file.localeCompare(b.file)).map((m) =>
    `def(${JSON.stringify(m.file)}, function (req) {\n${m.body.trimEnd()}\nreturn { ${m.names.join(', ')} };\n});`);
  return [
    '// GENERATED by scripts/build-screen.mjs from src/. Do not edit: change the sources and run npm run build.',
    '(function () {',
    "'use strict';",
    'var defs = {}, done = {};',
    'function def(name, fn) { defs[name] = fn; }',
    'function req(name) { if (!(name in done)) { if (!defs[name]) throw new Error("Missing module " + name); done[name] = null; done[name] = defs[name](req); } return done[name]; }',
    ...parts,
    `req(${JSON.stringify(ENTRY)});`,
    '})();',
    '',
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const out = build();
  const path = join(ROOT, OUT);
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(path, 'utf8'); } catch { /* missing */ }
    if (current !== out) { console.error(`${OUT} is out of date: run npm run build`); process.exit(1); }
    console.log(`${OUT} is up to date`);
  } else {
    writeFileSync(path, out);
    console.log(`wrote ${OUT} (${out.length} characters)`);
  }
}
